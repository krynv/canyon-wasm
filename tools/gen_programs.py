"""Generate assembly/programs.ts (the attack-wave tables) from the decompiled CGame.as."""
import os, re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
src = open(os.path.join(ROOT, 're', 'export', 'scripts', '__Packages', 'CGame.as'), encoding='utf-8').read()
src = re.sub(r'\s+', '', src)
body = src[src.index('staticvarPROGRAMS=newArray(') + len('staticvarPROGRAMS=newArray('):src.index(';functionCGame()')]
ALT = {'GROUND': 1, 'AIR': 2}
SIZE = {'TINY': 1, 'SMALL': 2, 'MEDIUM': 3, 'BIG': 4}
EFFECT = {'FAST': 1, 'SHIELD': 2, 'REPAIR': 3}
programs = []
for prog in body.split('newArray(')[1:]:
    waves = []
    for w in re.findall(r'\{([^}]*)\}', prog):
        f = dict(kv.split(':') for kv in w.split(','))
        waves.append((ALT[f['alt'].split('WAVE_ALT_')[1]], int(f['qty']), SIZE[f['size'].split('WAVE_SIZE_')[1]],
                      int(f['level']), EFFECT[f['effect'].split('WAVE_EFFECT_')[1]] if 'effect' in f else 0))
    programs.append(waves)

out = ['// GENERATED by tools/gen_programs.py from CGame.PROGRAMS — do not edit.',
       '// Each wave is five values: altitude, quantity, size, level, effect (0 = none).',
       'export const WAVE_FIELDS: i32 = 5;', '']
for i, waves in enumerate(programs):
    out.append('const PROGRAM_%d: StaticArray<i32> = [' % i)
    for w in waves:
        out.append('  %d, %d, %d, %d, %d,' % w)
    out.append('];')
out.append('')
out.append('export const PROGRAMS: StaticArray<StaticArray<i32>> = [%s];' % ', '.join('PROGRAM_%d' % i for i in range(len(programs))))
open(os.path.join(ROOT, 'assembly', 'programs.ts'), 'w').write('\n'.join(out) + '\n')
print([len(p) for p in programs])
